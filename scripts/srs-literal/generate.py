#!/usr/bin/env python3
"""Write Midnight/SHA256/SrsLiteral.lean: the first 2^13 monomial points of the public SRS
midnight-zk derives the SHA-256 preimage key from.

Usage: generate.py MIDNIGHT_ZK [--check]
MIDNIGHT_ZK is a midnight-zk checkout (only read); the SRS is
zk_stdlib/examples/assets/bls_filecoin_2p19. --check compares instead of writing.
"""
import hashlib
import sys
from pathlib import Path

K = 13
SRS_SHA256 = "0574a536c128142e89c0f28198d048145e2bb2bf645c8b81c8697cba445a1fb1"
P = 0x1a0111ea397fe69a4b1ba7b6434bacd764774b84f38512bf6730d2a0f6b0f6241eabfffeb153ffffb9feffffffffaaab
OUT = Path(__file__).resolve().parents[2] / "Midnight/SHA256/SrsLiteral.lean"


def fail(message):
    sys.exit(f"generate.py: {message}")


def read_srs(path):
    whole = Path(path).read_bytes()
    if hashlib.sha256(whole).hexdigest() != SRS_SHA256:
        fail("SRS file hash differs from the pinned public SRS")
    if int.from_bytes(whole[:4], "little") < K:
        fail("SRS is smaller than 2^13")
    prefix = whole[4:4 + 96 * 2 ** K]
    points = []
    for i in range(2 ** K):
        raw = prefix[96 * i:96 * (i + 1)]
        if raw[0] & 0xe0:
            fail(f"SRS point {i} is flagged (compressed or infinity)")
        x, y = int.from_bytes(raw[:48], "big"), int.from_bytes(raw[48:], "big")
        if not (x < P and y < P and (y * y - x ** 3 - 4) % P == 0):
            fail(f"SRS point {i} is not on the curve")
        points.append((x, y))
    return points, hashlib.sha256(prefix).hexdigest()


def render(points, prefix_hash):
    names, chunks = [], []
    for offset in range(0, len(points), 64):
        name = f"srsLiteral_{offset // 64:04d}"
        names.append(name)
        chunks.append(f"private def {name} : Array (Nat × Nat) := #[\n  " +
                      ",\n  ".join(f"({x}, {y})" for x, y in points[offset:offset + 64]) + "]\n")
    return f'''/-! Generated by scripts/srs-literal/generate.py; do not edit by hand.

`srsLiteral` is the first 2^13 monomial points of zk_stdlib/examples/assets/bls_filecoin_2p19
(file SHA-256 {SRS_SHA256}); the {96 * 2 ** K} point bytes after
its 4-byte header have SHA-256 {prefix_hash} (`KeyCheck.srs_anchor`).
Regenerate with `python3 scripts/srs-literal/generate.py MIDNIGHT_ZK`. -/

namespace Midnight.SHA256

''' + "\n".join(chunks) + f'''
def srsLiteralData : Array (Nat × Nat) := #[{', '.join(names)}].flatten

/-- The public monomial setup `[τ^i]G₁`, `i < 2^13`, as affine coordinates. -/
def srsLiteral : Array (Nat × Nat) := srsLiteralData

end Midnight.SHA256
'''


def main():
    args = [a for a in sys.argv[1:] if a != "--check"]
    if len(args) != 1:
        fail(__doc__)
    text = render(*read_srs(Path(args[0]) / "zk_stdlib/examples/assets/bls_filecoin_2p19"))
    if "--check" in sys.argv:
        if OUT.read_text() != text:
            fail(f"{OUT} differs from regeneration")
        print(f"{OUT.name} matches")
    else:
        OUT.write_text(text)
        print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
